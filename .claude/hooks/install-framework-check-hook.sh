#!/usr/bin/env bash
# Installs the composed pre-commit hook into this clone's hooks directory.
# Local to your clone, not committed. .claude/hooks/*.sh are the source of truth;
# re-run this after pulling hook changes or adding a new hook script.
# Refuses to overwrite an existing pre-commit hook that this installer did not create.
set -euo pipefail
REPO_ROOT="$(git rev-parse --show-toplevel)"
MARKER="quorum-hooks-managed"

HOOKS_DIR="$(git rev-parse --git-path hooks)"
case "$HOOKS_DIR" in
  /*) ;;
  *) HOOKS_DIR="$(cd "$REPO_ROOT" && cd "$HOOKS_DIR" 2>/dev/null && pwd || echo "$REPO_ROOT/$HOOKS_DIR")" ;;
esac
mkdir -p "$HOOKS_DIR"
TARGET="$HOOKS_DIR/pre-commit"

if [ -e "$TARGET" ] && ! grep -q "$MARKER" "$TARGET"; then
  echo "ERROR: $TARGET exists and was not created by this installer (no '$MARKER' marker)." >&2
  echo "Merge the framework check into it by hand, or move it aside and re-run." >&2
  exit 1
fi

cat > "$TARGET" <<'EOF'
#!/usr/bin/env bash
# quorum-hooks-managed: composed pre-commit hook.
# Generated by .claude/hooks/install-framework-check-hook.sh; re-run the installer to update.
set -e
REPO_ROOT="$(git rev-parse --show-toplevel)"

# 1) Agent and skill frontmatter check
if [ -f "$REPO_ROOT/.claude/hooks/pre-commit-framework-check.sh" ]; then
  bash "$REPO_ROOT/.claude/hooks/pre-commit-framework-check.sh"
fi

# Add further checks here, one "if [ -f ... ]; then bash ...; fi" block each.
EOF

chmod +x "$TARGET"
echo "Installed pre-commit hook at $TARGET"
